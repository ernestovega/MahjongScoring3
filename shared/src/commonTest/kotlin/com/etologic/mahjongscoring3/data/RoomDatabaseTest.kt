/**
 * Port of MS2 RoomDatabaseTest: Room DAOs and repositories on a real SQLite database
 * (Robolectric on Android, the simulator on iOS).
 */
class RoomDatabaseTest : PlatformTest() {

    private lateinit var db: AppDatabase
    private lateinit var games: RoomGamesRepository
    private lateinit var rounds: RoomRoundsRepository

    @BeforeTest
    fun setUp() {
        db = buildAppDatabase(testDatabaseBuilder(testFilePath("room-test.db")), testSqliteDriver())
        games = RoomGamesRepository(db.gamesDao())
        rounds = RoomRoundsRepository(db.roundsDao())
    }

    @AfterTest
    fun tearDown() = db.close()

    @Test
    fun idsAreAutoGeneratedFrom1() = runTest {
        assertThat(games.insertOne(GameRecord()).getOrThrow()).isEqualTo(1L)
        assertThat(games.insertOne(GameRecord()).getOrThrow()).isEqualTo(2L)
        assertThat(rounds.insertOne(RoundRecord(gameId = 1, roundId = 0)).getOrThrow()).isTrue()
        assertThat(rounds.getGameRounds(1).getOrThrow().single().roundId).isEqualTo(1L)
    }

    @Test
    fun gamesAreListedByStartDateDescThenIdDesc() = runTest {
        games.insertOne(GameRecord(startDate = 1000)).getOrThrow()
        games.insertOne(GameRecord(startDate = 3000)).getOrThrow()
        games.insertOne(GameRecord(startDate = 1000)).getOrThrow()
        assertThat(games.getAllFlow().first().map { it.gameId }).containsExactly(2L, 3L, 1L).inOrder()
    }

    @Test
    fun gameFieldsRoundTripIncludingNullEndDateAndDefaultName() = runTest {
        val game = GameRecord(nameP1 = "A", nameP2 = "B", nameP3 = "C", nameP4 = "D", startDate = 123, endDate = null)
        val id = games.insertOne(game).getOrThrow()
        val stored = games.getOne(id).getOrThrow()
        assertThat(stored).isEqualTo(game.copy(gameId = id))
        assertThat(stored.gameName).isEmpty()
        assertThat(games.updateOne(stored.copy(endDate = 456, gameName = "x")).getOrThrow()).isTrue()
        assertThat(games.getOneFlow(id).first()?.endDate).isEqualTo(456L)
        assertThat(games.updateOne(GameRecord(gameId = 99)).getOrThrow()).isFalse()
    }

    @Test
    fun windsAreStoredAsTheirCodesAndNullMeansOngoing() = runTest {
        val gameId = games.insertOne(GameRecord()).getOrThrow()
        rounds.insertOne(RoundRecord(gameId, 0, TableWinds.NORTH, TableWinds.NONE, 12, 1, 2, 3, 4)).getOrThrow()
        rounds.insertOne(RoundRecord(gameId, 0)).getOrThrow()
        val raw = db.useReaderConnection { connection ->
            connection.usePrepared("SELECT winnerInitialSeat, discarderInitialSeat FROM Rounds ORDER BY roundId") { statement ->
                buildList {
                    while (statement.step()) {
                        add(
                            (if (statement.isNull(0)) null else statement.getInt(0)) to
                                (if (statement.isNull(1)) null else statement.getInt(1))
                        )
                    }
                }
            }
        }
        assertThat(raw).containsExactly(3 to -1, null to null).inOrder()
        val stored = rounds.getGameRounds(gameId).getOrThrow()
        assertThat(stored[0].winnerInitialSeat).isEqualTo(TableWinds.NORTH)
        assertThat(stored[0].discarderInitialSeat).isEqualTo(TableWinds.NONE)
        assertThat(listOf(stored[0].penaltyP1, stored[0].penaltyP2, stored[0].penaltyP3, stored[0].penaltyP4)).containsExactly(1, 2, 3, 4).inOrder()
        assertThat(stored[1].isOngoing()).isTrue()
    }

    @Test
    fun roundsRequireAnExistingGameForeignKey() = runTest {
        val result = rounds.insertOne(RoundRecord(gameId = 42, roundId = 0))
        // MS2 gets android.database.sqlite.SQLiteConstraintException; in KMP the type depends on the driver.
        assertThat(result.isFailure).isTrue()
        assertThat(result.exceptionOrNull()?.message.orEmpty().uppercase().contains("FOREIGN KEY")).isTrue()
    }

    @Test
    fun aGameWithRoundsCannotBeDeletedBeforeItsRounds() = runTest {
        val gameId = games.insertOne(GameRecord()).getOrThrow()
        rounds.insertOne(RoundRecord(gameId, 0)).getOrThrow()
        assertThat(games.deleteOne(gameId).isFailure).isTrue()
        DeleteGameUseCase(games, rounds)(gameId).getOrThrow()
        assertThat(games.getAllFlow().first()).isEmpty()
        assertThat(rounds.getAllFlow().first()).isEmpty()
    }

    @Test
    fun roundUpdatesAndDeletesReportWhetherARowChanged() = runTest {
        val gameId = games.insertOne(GameRecord()).getOrThrow()
        rounds.insertOne(RoundRecord(gameId, 0)).getOrThrow()
        val round = rounds.getGameRounds(gameId).getOrThrow().single()
        assertThat(rounds.updateOne(RoundRecord(gameId, round.roundId, TableWinds.EAST, TableWinds.SOUTH, 8)).getOrThrow()).isTrue()
        assertThat(rounds.getOne(round.roundId).getOrThrow().handPoints).isEqualTo(8)
        assertThat(rounds.updateOne(RoundRecord(gameId, 999, null, null)).getOrThrow()).isFalse()
        assertThat(rounds.deleteOne(999).getOrThrow()).isFalse()
        assertThat(rounds.deleteOne(round.roundId).getOrThrow()).isTrue()
        assertThat(rounds.deleteGameRounds(gameId).getOrThrow()).isTrue()
        assertThat(rounds.getOne(round.roundId).isFailure).isTrue()
    }

    /** Same golden reports as the pure domain tests, but going through Room: proves both paths agree. */
    @Test
    fun importingEveryGoldenScenarioIntoRoomReproducesItsReport() = runTest {
        val importer = ImportGamesFromJsonUseCase(games, rounds, DeleteGameUseCase(games, rounds))
        val getOne = GetOneGameFlowUseCase(games, rounds)
        GameScenarios.all.forEach { scenario ->
            val dir = "scenarios/${scenario.name}"
            val id = importer(Goldens.read("$dir/game.json")).getOrThrow().single()
            Goldens.assertMatches("$dir/report.txt", GameReport.render(getOne(id).first()))
        }
        assertThat(GetAllGamesFlowUseCase(games, rounds)().first()).hasSize(GameScenarios.all.size)
    }
}
